const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());
  await page.route('https://fonts.gstatic.com/**',route=>route.abort());
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('inveys-workspace-v1')));
  const nav=async target=>{await page.locator(`#navigation [data-page="${target}"]`).click();await page.waitForFunction(target=>document.querySelector('#navigation .active')?.dataset.page===target,target);};
  const modal=page.locator('#modal');
  await page.goto('http://127.0.0.1:3000',{waitUntil:'domcontentloaded'});
  await page.waitForSelector('.metrics-grid');
  await page.locator('#language-switch').selectOption('en');
  assert.equal((await state()).accounts.length,4);
  assert.ok((await page.locator('#main').textContent()).includes('$224,370'));
  await page.locator('#theme-switch').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.locator('#theme-switch').click();
  await page.locator('#language-switch').selectOption('id');
  assert.equal(await page.locator('html').getAttribute('lang'),'id');
  assert.ok((await page.locator('#navigation').textContent()).includes('Kartu kredit'));
  await page.locator('#language-switch').selectOption('en');
  await page.screenshot({path:path.resolve(__dirname,'../../inveys-desktop.png'),fullPage:true});
  console.log('PASS dashboard renders and financial position is correct');

  await page.locator('[data-action="period:12"]').click();
  assert.equal(await page.locator('.chart-container svg text').filter({hasText:'Nov'}).count(),1);
  await page.locator('[data-action="privacy"]').click();
  assert.equal(await page.locator('body.privacy-on').count(),1);
  await page.locator('[data-action="privacy"]').click();

  await nav('accounts');
  await page.locator('[data-action="account-new"]').click();
  await modal.locator('[name="name"]').fill('Browser test account');
  await modal.locator('[name="balance"]').fill('123.45');
  await modal.locator('button[type="submit"]').click();
  const account=(await state()).accounts.find(a=>a.name==='Browser test account');
  assert.equal(account.balance,12345);
  await page.reload();
  assert.ok((await page.locator('#main').textContent()).includes('Browser test account'));
  console.log('PASS account entry stores exact cents and survives reload');

  await nav('transactions');
  const before=await state();
  await page.locator('[data-action="transaction-new"]').click();
  assert.equal(await modal.locator('#destination-field').isVisible(),false);
  await modal.locator('[name="name"]').fill('Browser transfer');
  await modal.locator('[name="kind"]').selectOption('transfer');
  assert.equal(await modal.locator('#destination-field').isVisible(),true);
  await modal.locator('[name="amount"]').fill('50.25');
  await modal.locator('[name="accountId"]').selectOption('a1');
  await modal.locator('[name="targetId"]').selectOption('a2');
  await modal.locator('button[type="submit"]').click();
  const after=await state();
  assert.equal(after.accounts.find(a=>a.id==='a1').balance,before.accounts.find(a=>a.id==='a1').balance-5025);
  assert.equal(after.accounts.find(a=>a.id==='a2').balance,before.accounts.find(a=>a.id==='a2').balance+5025);
  assert.equal(after.accounts.reduce((s,a)=>s+a.balance,0),before.accounts.reduce((s,a)=>s+a.balance,0));
  await page.locator('#transaction-search').fill('Browser transfer');
  assert.equal(await page.locator('#transaction-rows tr').count(),1);
  console.log('PASS transfers preserve assets and search filters records');

  await nav('goals');
  await page.locator('[data-action="fund:g1"]').click();
  await modal.locator('[name="amount"]').fill('99999999');
  await modal.locator('button[type="submit"]').click();
  assert.ok((await modal.locator('#form-error').textContent()).includes('exceeds'));
  await modal.locator('[name="amount"]').fill('100');
  await modal.locator('button[type="submit"]').click();
  assert.equal((await state()).goals.find(g=>g.id==='g1').saved,1810000);
  console.log('PASS goal allocation rejects overcommitment and records valid allocation');

  await nav('scenarios');
  const snapshot=JSON.stringify(await state());
  const beforeChart=await page.locator('#scenario-summary').textContent();
  await page.locator('#oneTime').evaluate(el=>{el.value=50000;el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.notEqual(await page.locator('#scenario-summary').textContent(),beforeChart);
  assert.equal(JSON.stringify(await state()),snapshot);
  await page.screenshot({path:path.resolve(__dirname,'../../inveys-scenarios.png'),fullPage:true});
  console.log('PASS scenario updates projections without changing records');

  await nav('montecarlo');
  await page.locator('#field-initial').fill('1000');
  await page.locator('#field-monthly').fill('100');
  await page.locator('#field-years').fill('1');
  await page.locator('#field-mean').fill('0');
  await page.locator('#field-volatility').fill('0');
  await page.locator('#field-inflation').fill('0');
  await page.locator('#field-target').fill('2200');
  await page.locator('#mc-form button[type=submit]').click();
  assert.ok((await page.locator('#mc-result').textContent()).includes('100.0%'));
  await nav('cards');
  assert.ok((await page.locator('#main').textContent()).includes('Northstar Rewards'));
  const calendar=page.waitForEvent('download');
  await page.locator('[data-action=card-calendar]').click();
  assert.ok((await calendar).suggestedFilename().endsWith('.ics'));
  console.log('PASS Monte Carlo results and credit-card calendar export');
  await nav('debt');
  const base=await page.locator('#debt-results-d3').textContent();
  await page.locator('#debt-extra-d3').evaluate(el=>{el.value=500;el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.notEqual(await page.locator('#debt-results-d3').textContent(),base);
  console.log('PASS debt slider recalculates payoff');

  await nav('household');
  const openBefore=(await state()).tasks.filter(t=>!t.done).length;
  await page.locator('[data-task="task1"]').check();
  assert.equal((await state()).tasks.filter(t=>!t.done).length,openBefore-1);
  await nav('copilot');
  await page.locator('[data-question="What is my financial position?"]').click();
  assert.ok((await page.locator('#chat-messages').textContent()).includes('manual balance snapshots'));
  await page.locator('#chat-question').fill('<img src=x onerror=alert(1)>');
  await page.locator('#chat-form button').click();
  assert.equal(await page.locator('.chat-message.user img').count(),0);
  console.log('PASS household completion and safe grounded copilot');

  await page.locator('#search-button').click();
  await page.locator('#global-search').fill('Browser test account');
  await page.locator('.search-result').click();
  assert.equal(await modal.isVisible(),false);
  assert.equal(await page.locator('#navigation .active').getAttribute('data-page'),'accounts');

  await page.locator('#settings-button').click();
  const download=page.waitForEvent('download');
  await page.locator('[data-action="export"]').click();
  assert.ok((await download).suggestedFilename().endsWith('.json'));
  const original=await state();
  await page.locator('#import-file').setInputFiles({name:'workspace.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(original))});
  await page.waitForFunction(()=>document.querySelector('#modal').open);
  assert.ok((await modal.locator('#modal-title').textContent()).includes('Restore'));
  await modal.locator('button[type="submit"]').click();
  assert.equal((await state()).transactions.length,original.transactions.length);
  console.log('PASS export and validated JSON restore');

  await page.locator('[data-action="empty-workspace"]').click();
  await modal.locator('[name="name"]').fill('Personal finance');
  await modal.locator('[name="currency"]').selectOption('IDR');
  await modal.locator('button[type="submit"]').click();
  const empty=await state();
  assert.equal(empty.currency,'IDR');assert.equal(empty.accounts.length,0);assert.equal(empty.demo,false);
  for(const target of ['home','accounts','cashflow','transactions','goals','debt','scenarios','montecarlo','cards','household','copilot'])await nav(target);
  console.log('PASS empty workspace and every page handles no records');

  await page.locator('#settings-button').click();
  await page.locator('[data-action="reset-demo"]').click();
  await modal.locator('button[type="submit"]').click();
  await nav('home');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.resolve(__dirname,'../../inveys-mobile.png'),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.locator('#menu-button').click();
  await nav('goals');
  assert.equal(await page.locator('#sidebar.open').count(),0);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  console.log('PASS responsive layout and mobile navigation');
  assert.deepEqual(errors,[]);
  console.log('PASS no browser runtime errors');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
